#!/usr/bin/env python3
"""BTA-005 - MDL Process Memory Probe.

Question:
Can a deterministic sampler be used as process memory: store a small generator
plus residual corrections instead of storing every raw receipt?

Safe reading:
- This is conditional compression: it works only when the action trace is
  actually generated by a compact process that the model class can express.
- It does not make phi unique.
- It does not authorize anything in Aukora. It is proposal/memory telemetry only.
"""

from __future__ import annotations

import csv
import json
import math
import random
import statistics
import zlib
from dataclasses import dataclass
from pathlib import Path

import numpy as np

import ghp_phi_coordinate_sampler_probe as bta3


ROOT = Path(__file__).resolve().parent
OUT = ROOT / "ghp_mdl_process_memory_probe_outputs"
TOKEN_COUNT = bta3.TOKEN_COUNT
PHI = bta3.PHI
ALPHA_PHI = 1.0 / PHI
ALPHA_SQRT2 = math.sqrt(2.0) - 1.0
WINDOW = 128
SEEDS = [1618, 2718, 3141, 4159]
REGIMES = ["smooth", "balanced", "spiky", "bursty", "drifting", "inverted"]


@dataclass(frozen=True)
class Result:
    probe: str
    status: str
    metric: str
    value: str
    safe_read: str


def compressed_bits(payload: object) -> int:
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return len(zlib.compress(raw, level=9)) * 8


def raw_json_bits(payload: object) -> int:
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return len(raw) * 8


def candidate_generators() -> dict[str, float | str]:
    return {
        "phi_rotation": ALPHA_PHI,
        "sqrt2_rotation": ALPHA_SQRT2,
        "e_minus_2": math.e - 2.0,
        "pi_minus_3": math.pi - 3.0,
        "periodic_lattice": "periodic_lattice",
        "argmax": "argmax",
    }


def van_der_corput(index: int, base: int = 2) -> float:
    return bta3.van_der_corput(index, base)


def cdf_token(x: float, p: np.ndarray) -> int:
    return bta3.choose_from_cdf(x, p)


def public_record(step: int, regime: str, mode: str, token: int, p: np.ndarray) -> dict[str, object]:
    entropy = -float(np.sum(p * np.log2(np.maximum(p, 1e-12)))) / math.log2(TOKEN_COUNT)
    confidence = float(np.max(p))
    return {
        "t": step,
        "regime": regime,
        "mode": mode,
        "action": token,
        "entropy_bucket": round(entropy, 2),
        "confidence_bucket": round(confidence, 2),
    }


def generate_tokens(generator: str, steps: int, seed: int, regimes: list[str]) -> tuple[list[int], list[dict[str, object]]]:
    rng = random.Random(seed * 811 + len(generator))
    x = (seed % 1009) / 1009.0
    tokens: list[int] = []
    records: list[dict[str, object]] = []
    for step in range(steps):
        regime = regimes[step % len(regimes)]
        p = bta3.target_distribution(step, regime, seed)
        mode = bta3.mode_at(step, regime, p)
        if generator == "phi_rotation":
            x = (x + ALPHA_PHI) % 1.0
            token = cdf_token(x, p)
        elif generator == "sqrt2_rotation":
            x = (x + ALPHA_SQRT2) % 1.0
            token = cdf_token(x, p)
        elif generator == "vdc_base2":
            token = cdf_token(van_der_corput(step, 2), p)
        elif generator == "prng":
            token = cdf_token(rng.random(), p)
        elif generator == "argmax":
            token = int(np.argmax(p))
            if step % 53 == 0:
                token = (token + 1) % TOKEN_COUNT
        elif generator == "mixed_low_discrepancy":
            alpha = ALPHA_PHI if (step // 257) % 2 == 0 else ALPHA_SQRT2
            x = (x + alpha) % 1.0
            token = cdf_token(x, p)
        elif generator == "human_jitter":
            token = int(np.argmax(p))
            if rng.random() < 0.18:
                token = cdf_token(rng.random(), p)
        else:
            raise ValueError(generator)
        tokens.append(token)
        records.append(public_record(step, regime, mode, token, p))
    return tokens, records


def predict_tokens(candidate: str, steps: int, seed: int, regimes: list[str]) -> list[int]:
    value = candidate_generators()[candidate]
    x = (seed % 1009) / 1009.0
    tokens: list[int] = []
    for step in range(steps):
        regime = regimes[step % len(regimes)]
        p = bta3.target_distribution(step, regime, seed)
        if isinstance(value, float):
            x = (x + value) % 1.0
            token = cdf_token(x, p)
        elif value == "periodic_lattice":
            token = cdf_token(((step % TOKEN_COUNT) + 0.5) / TOKEN_COUNT, p)
        elif value == "argmax":
            token = int(np.argmax(p))
        else:
            raise ValueError(candidate)
        tokens.append(token)
    return tokens


def residual_patch_bits(predicted: list[int], actual: list[int]) -> tuple[int, float]:
    mismatches = sum(1 for a, b in zip(predicted, actual) if a != b)
    position_bits = math.ceil(math.log2(max(2, len(actual))))
    token_bits = math.ceil(math.log2(TOKEN_COUNT))
    # A generous patch stream: each mismatch stores its position and corrected token.
    return int(mismatches * (position_bits + token_bits)), mismatches / len(actual)


def best_mdl(tokens: list[int], seed: int, regimes: list[str]) -> dict[str, float | str]:
    best: dict[str, float | str] | None = None
    for candidate in candidate_generators():
        predicted = predict_tokens(candidate, len(tokens), seed, regimes)
        patch_bits, mismatch_rate = residual_patch_bits(predicted, tokens)
        model_bits = 320
        mdl_bits = model_bits + patch_bits
        row: dict[str, float | str] = {
            "candidate": candidate,
            "mdl_bits": mdl_bits,
            "patch_bits": patch_bits,
            "mismatch_rate": mismatch_rate,
        }
        if best is None or float(row["mdl_bits"]) < float(best["mdl_bits"]):
            best = row
    assert best is not None
    return best


def run_trace_family(family: str, steps: int, seed: int) -> dict[str, float | str]:
    regimes = REGIMES if family != "single_regime" else ["smooth"]
    source = "phi_rotation" if family == "single_regime" else family
    tokens, records = generate_tokens(source, steps, seed, regimes)
    raw_bits = raw_json_bits(records)
    zlib_bits = compressed_bits(records)
    action_zlib_bits = compressed_bits(tokens)
    best = best_mdl(tokens, seed, regimes)
    return {
        "family": family,
        "seed": seed,
        "steps": steps,
        "raw_json_bits": raw_bits,
        "raw_zlib_bits": zlib_bits,
        "action_zlib_bits": action_zlib_bits,
        "best_candidate": best["candidate"],
        "mdl_bits": best["mdl_bits"],
        "patch_bits": best["patch_bits"],
        "mismatch_rate": best["mismatch_rate"],
        "mdl_vs_zlib": float(best["mdl_bits"]) / zlib_bits,
        "mdl_vs_action_zlib": float(best["mdl_bits"]) / action_zlib_bits,
        "mdl_vs_raw_json": float(best["mdl_bits"]) / raw_bits,
    }


def aggregate(rows: list[dict[str, float | str]]) -> list[dict[str, float | str]]:
    grouped: dict[str, list[dict[str, float | str]]] = {}
    for row in rows:
        grouped.setdefault(str(row["family"]), []).append(row)
    out: list[dict[str, float | str]] = []
    for family, items in grouped.items():
        out.append(
            {
                "family": family,
                "best_candidate_mode": statistics.mode(str(item["best_candidate"]) for item in items),
                "mdl_vs_zlib_mean": statistics.fmean(float(item["mdl_vs_zlib"]) for item in items),
                "mdl_vs_zlib_std": statistics.pstdev(float(item["mdl_vs_zlib"]) for item in items),
                "mismatch_rate_mean": statistics.fmean(float(item["mismatch_rate"]) for item in items),
                "mismatch_rate_std": statistics.pstdev(float(item["mismatch_rate"]) for item in items),
                "raw_zlib_bits_mean": statistics.fmean(float(item["raw_zlib_bits"]) for item in items),
                "action_zlib_bits_mean": statistics.fmean(float(item["action_zlib_bits"]) for item in items),
                "mdl_bits_mean": statistics.fmean(float(item["mdl_bits"]) for item in items),
                "mdl_vs_action_zlib_mean": statistics.fmean(float(item["mdl_vs_action_zlib"]) for item in items),
                "mdl_vs_action_zlib_std": statistics.pstdev(float(item["mdl_vs_action_zlib"]) for item in items),
            }
        )
    return sorted(out, key=lambda row: float(row["mdl_vs_zlib_mean"]))


def write_csv(path: Path, rows: list[dict[str, float | str]]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def classify_results(summary: list[dict[str, float | str]]) -> list[Result]:
    by_family = {str(row["family"]): row for row in summary}
    phi_ratio = float(by_family["phi_rotation"]["mdl_vs_action_zlib_mean"])
    prng_ratio = float(by_family["prng"]["mdl_vs_action_zlib_mean"])
    mixed_ratio = float(by_family["mixed_low_discrepancy"]["mdl_vs_action_zlib_mean"])
    human_ratio = float(by_family["human_jitter"]["mdl_vs_action_zlib_mean"])
    argmax_ratio = float(by_family["argmax"]["mdl_vs_action_zlib_mean"])

    mdl_status = "PASS" if phi_ratio < 0.20 and prng_ratio > 1.0 else "MIXED"
    if phi_ratio >= 0.50 or prng_ratio <= 0.80:
        mdl_status = "FAIL"

    specificity_status = "PASS" if mixed_ratio > phi_ratio * 3.0 and human_ratio > phi_ratio * 3.0 else "MIXED"

    argmax_status = "PASS" if argmax_ratio < 0.50 else "MIXED"

    return [
        Result(
            "BTA-005A",
            mdl_status,
            "rule+residual vs compressed action history",
            f"phi_ratio={phi_ratio:.4f}; prng_ratio={prng_ratio:.4f}",
            "Process memory is real only when the action trace is generated by a compact candidate rule; PRNG should not compress under a deterministic rule class.",
        ),
        Result(
            "BTA-005B",
            specificity_status,
            "mixed/human traces resist single-rule compression",
            f"mixed_ratio={mixed_ratio:.4f}; human_ratio={human_ratio:.4f}; phi_ratio={phi_ratio:.4f}",
            "The MDL lane must preserve residuals honestly; mixed or human-jitter traces should cost more than a clean generator trace.",
        ),
        Result(
            "BTA-005C",
            argmax_status,
            "non-phi compact policy control",
            f"argmax_ratio={argmax_ratio:.4f}",
            "If a non-phi rule generated the trace, MDL should find that too. This prevents phi-only overclaiming.",
        ),
    ]


def write_report(results: list[Result], summary: list[dict[str, float | str]]) -> None:
    lines = [
        "# BTA-005 MDL Process Memory Probe",
        "",
        "Toy telemetry only. This tests whether generator-plus-residual memory can beat compressed public action history, while also reporting full-receipt compression as context.",
        "",
        "| Probe | Status | Metric | Value | Safe Read |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in results:
        lines.append(f"| {r.probe} | {r.status} | {r.metric} | `{r.value}` | {r.safe_read} |")

    lines += [
        "",
        "## Family Summary",
        "",
        "| Trace Family | Best Candidate Mode | MDL / Action Zlib | MDL / Receipt Zlib | Mismatch | Action Zlib Bits | MDL Bits |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in summary:
        lines.append(
            f"| {row['family']} | {row['best_candidate_mode']} | {float(row['mdl_vs_action_zlib_mean']):.4f} | "
            f"{float(row['mdl_vs_zlib_mean']):.4f} | {float(row['mismatch_rate_mean']):.4f} | "
            f"{float(row['action_zlib_bits_mean']):.1f} | {float(row['mdl_bits_mean']):.1f} |"
        )

    lines += [
        "",
        "## Safe Read",
        "",
        "The useful compression object is not phi digits or hidden infinite data. It is MDL process memory: store a compact rule when the trace was generated by that rule, then store residual corrections for everything the rule failed to predict.",
        "",
        "Aukora promotion should compare `rule_bits + residual_bits` against compressed raw receipt history on sandbox traces only. The result may guide memory summarization, never authority.",
    ]
    (OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_handoff(results: list[Result]) -> None:
    text = f"""# BTA-005 Aukora Handoff

Candidate to test in Aukora later:

`MDL process memory = generator_id + seed/state + residual corrections`

Use only on public sandbox traces. Compare:

- raw compressed receipt history
- structural summary memory
- phi-rotation generator + residuals
- sqrt2 / vdc / argmax / PRNG controls + residuals

Promotion metrics:

- `rule_bits + residual_bits < compressed_raw_receipt_bits`
- prediction accuracy does not collapse
- residuals remain explicit, auditable, and replayable
- private/authority reconstruction stays near chance
- no sampler or memory summary can authorize action

Do not promote:

- phi digits as memory
- generator compression as arbitrary-payload compression
- sampler state as identity or authority

Latest lab statuses:

{chr(10).join(f"- {r.probe}: {r.status} - {r.value}" for r in results)}
"""
    (OUT / "AUKORA_HANDOFF.md").write_text(text, encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, float | str]] = []
    families = ["phi_rotation", "sqrt2_rotation", "vdc_base2", "prng", "argmax", "mixed_low_discrepancy", "human_jitter", "single_regime"]
    for family in families:
        for seed in SEEDS:
            rows.append(run_trace_family(family, 4096, seed))
    summary = aggregate(rows)
    results = classify_results(summary)

    write_csv(OUT / "trace_runs.csv", rows)
    write_csv(OUT / "family_summary.csv", summary)
    write_csv(OUT / "summary.csv", [r.__dict__ for r in results])
    write_report(results, summary)
    write_handoff(results)

    for r in results:
        print(f"{r.probe}: {r.status} | {r.metric}: {r.value}")
    print(f"report: {OUT / 'report.md'}")


if __name__ == "__main__":
    main()
